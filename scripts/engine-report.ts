/* bun scripts/engine-report.ts — registry validation + live report.
 * Also regenerates docs/ENGINE-REGISTRY.md (the full machine-readable
 * listing of every feature and variable). */
import fs from "node:fs"
import { computeFeatures } from "../src/lib/engine/features"
import { computeScores } from "../src/lib/engine/scores"
import { resolveGameConfig } from "../src/lib/engine/gameConfig"
import { decide } from "../src/lib/engine/decide"
import { GAME_VARS } from "../src/lib/engine/gameVars"
import { EXPERIMENTS } from "../src/lib/engine/bandit"

async function main() {
  const fr = await computeFeatures("user_1")
  const ids = new Set(fr.features.map((f) => f.id))
  const scores = await computeScores(fr, "user_1")
  const cfg = await resolveGameConfig(fr, scores)
  const d = await decide(fr, scores, cfg, "user_1")

  const uniqueVars = new Set(GAME_VARS.map((v) => v.id)).size
  const families = fr.byCat.map((c) => `${c.cat.padEnd(10)} ${c.count}`).join("\n  ")
  const domainsMap = GAME_VARS.reduce<Record<string, number>>((acc, v) => {
    acc[v.domain] = (acc[v.domain] ?? 0) + 1
    return acc
  }, {})
  const domains = Object.entries(domainsMap).map(([k, n]) => `${k.padEnd(12)} ${n}`).join("\n  ")

  // ── console report ──
  console.log("╔══════════════════════════════════════════════╗")
  console.log("║   THE SCRIBE'S LEDGER — REGISTRY REPORT      ║")
  console.log("╚══════════════════════════════════════════════╝")
  console.log(`retention & loyalty features : ${fr.features.length} (unique: ${ids.size}) ${ids.size === fr.features.length ? "✓ ≥500" : "✗ DUPLICATES"}`)
  console.log(`gamification variables       : ${GAME_VARS.length} (unique: ${uniqueVars}) ${uniqueVars === GAME_VARS.length ? "✓ ≥500" : "✗ DUPLICATES"}`)
  console.log(`experiments (bandit contexts): ${Object.keys(EXPERIMENTS).length}`)
  console.log(`\nfeature families:\n  ${families}`)
  console.log(`\ngamification domains:\n  ${domains}`)
  console.log(`\ncurrent user scores:`)
  console.log(`  churn ${(scores.churnRisk * 100).toFixed(0)}% · engagement ${(scores.engagement * 100).toFixed(0)}% · loyalty ${scores.loyalty.toFixed(0)}/100 (${scores.loyaltyTierName})`)
  console.log(`  wtp ${(scores.wtp * 100).toFixed(0)}% · ltv90 $${scores.ltv90} · burnout ${(scores.burnoutRisk * 100).toFixed(0)}% · segments: ${scores.segments.join(", ")}`)
  const personalizedAway = Object.keys(cfg).filter((k) => {
    const gv = GAME_VARS.find((v) => v.id === k)
    return gv && gv.def !== cfg[k]
  }).length
  console.log(`\nresolved config: ${Object.keys(cfg).length} values · ${personalizedAway} personalized away from default`)
  console.log(`NBAs: ${d.nba.map((n) => `${n.kind}(${n.priority.toFixed(1)})`).join(", ") || "none"}`)

  // ── regenerate docs/ENGINE-REGISTRY.md ──
  const lines: string[] = []
  lines.push("# The Scribe's Ledger — full registry")
  lines.push("")
  lines.push(`> Auto-generated by \`bun scripts/engine-report.ts\` — ${fr.features.length} features, ${GAME_VARS.length} gamification variables.`)
  lines.push("")
  lines.push("## Retention & loyalty features")
  lines.push("")
  lines.push("| # | id | family | signal |")
  lines.push("|---|----|--------|--------|")
  fr.features.forEach((f, i) => lines.push(`| ${i + 1} | \`${f.id}\` | ${f.cat} | ${f.desc} |`))
  lines.push("")
  lines.push("## Gamification variables")
  lines.push("")
  lines.push("| # | id | domain | default | description |")
  lines.push("|---|----|--------|---------|-------------|")
  GAME_VARS.forEach((v, i) => lines.push(`| ${i + 1} | \`${v.id}\` | ${v.domain} | \`${String(v.def)}\` | ${v.desc} |`))
  lines.push("")
  lines.push("## Experiments (Thompson sampling)")
  lines.push("")
  lines.push("| context | arms |")
  lines.push("|---|---|")
  for (const [ctx, arms] of Object.entries(EXPERIMENTS)) lines.push(`| \`${ctx}\` | ${arms.map((a) => `\`${a}\``).join(" · ")} |`)
  fs.writeFileSync("docs/ENGINE-REGISTRY.md", lines.join("\n") + "\n")
  console.log("\n✓ docs/ENGINE-REGISTRY.md regenerated")
}

main()
  .catch((e) => {
    console.error(e)
    process.exit(1)
  })
